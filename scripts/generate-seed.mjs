// Writes supabase/seed.sql with made-up data. Same seed, same output.
import { writeFileSync } from 'node:fs'

const CLIENT_COUNT = 212
const COMPANY_ID = '00000000-0000-4000-8000-000000000001'
const FIRST_NAMES = ['Ada', 'Bram', 'Cleo', 'Dov', 'Esme', 'Finn', 'Gia', 'Hal', 'Ines', 'Jory', 'Kit', 'Lev', 'Mira', 'Nico', 'Oona', 'Pim', 'Quin', 'Rhea', 'Sol', 'Tove']
const LAST_NAMES = ['Ashdown', 'Brindle', 'Corvel', 'Dunmore', 'Elsby', 'Fairlow', 'Garnet', 'Hollis', 'Ivers', 'Juno', 'Kestrel', 'Larkin', 'Morrow', 'Nettle', 'Orrin', 'Pell', 'Quarry', 'Rook', 'Sable', 'Thorne']
const STREETS = ['Example Lane', 'Sample Road', 'Fictional Ave', 'Placeholder St', 'Demo Close', 'Mock Terrace']
const NOTES = ['Key under the mat', 'Dog in the garden', 'Office, after 6 pm only', 'Bring own vacuum', null, null, null]

const random = createRandom(20260611)

const rows = Array.from({ length: CLIENT_COUNT }, (_, index) => {
  const name = `${pick(FIRST_NAMES)} ${pick(LAST_NAMES)}`
  // 555-01xx numbers are reserved for fiction.
  const phone = `+1 555 01${String(index % 100).padStart(2, '0')}`
  const address = `${1 + Math.floor(random() * 240)} ${pick(STREETS)}, Sampletown`
  const note = pick(NOTES)
  return `('${COMPANY_ID}', '${name}', '${phone}', '${address}', ${note ? `'${note}'` : 'null'})`
})

const sql = [
  '-- Generated by scripts/generate-seed.mjs. All names, phones and addresses are made up.',
  `insert into companies (id, name, plan) values ('${COMPANY_ID}', 'Brightside Cleaning (sample)', 'free');`,
  '',
  'insert into clients (company_id, full_name, phone, address, notes) values',
  `${rows.join(',\n')};`,
  '',
].join('\n')

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)

function pick(list) {
  return list[Math.floor(random() * list.length)]
}

function createRandom(seed) {
  let state = seed
  return function next() {
    state = (state * 1664525 + 1013904223) % 4294967296
    return state / 4294967296
  }
}
